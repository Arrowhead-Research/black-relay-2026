#!/usr/bin/env bash
# Regenerate docker/requirements-*.lock.txt from a REAL resolver run (pip-compile = pip's resolver) inside the image's
# own base image, so the Python version and environment markers are the ones the image will install under (a lock made
# on a different Python silently misses conditional dependencies such as typing_extensions on 3.12).
# Hashes cover every release file on PyPI for the pinned versions (all platforms), so one lock serves amd64 and arm64.
#
#   docker/relock.sh                 # run from anywhere; needs docker and network access to pypi.org
#   CA_BUNDLE=/path/ca.pem docker/relock.sh     # behind an intercepting proxy
#
# Review the diff, then rebuild all images (each Dockerfile imports its service module at build time, so a lock that is
# missing a dependency fails the BUILD).
set -euo pipefail
cd "$(dirname "$0")"
BASE=$(sed -n 's/^ARG PY_BASE=//p' Dockerfile.outbound)          # the same digest-pinned base the images use
args=(--rm --network host -v "$PWD:/w")
if [ -n "${CA_BUNDLE:-}" ]; then
  args+=(-v "$CA_BUNDLE:/ca.pem:ro" -e PIP_CERT=/ca.pem -e SSL_CERT_FILE=/ca.pem)
fi
[ -n "${HTTPS_PROXY:-}" ] && args+=(-e "HTTPS_PROXY=$HTTPS_PROXY")
docker run "${args[@]}" "$BASE" sh -ec '
  python --version
  pip install -q --disable-pip-version-check pip-tools==7.5.0
  cd /w
  for n in adapter normalizer outbound; do
    pip-compile --quiet --generate-hashes --allow-unsafe --strip-extras --no-header \
        --output-file "requirements-$n.lock.txt" "requirements-$n.txt"
    { printf "# Generated by docker/relock.sh (pip-compile, %s) from requirements-%s.txt. DO NOT EDIT BY HAND.\n" \
        "$(python -c "import platform;print(\"Python \"+platform.python_version())")" "$n"
      printf "# Install with: pip install --require-hashes --no-deps -r <this file>\n"
      cat "requirements-$n.lock.txt"; } > "requirements-$n.lock.tmp" && mv "requirements-$n.lock.tmp" "requirements-$n.lock.txt"
  done'
